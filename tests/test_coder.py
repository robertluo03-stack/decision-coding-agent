def test_execution_visualization() -> None:
    """验证可视化相关代码结构正确。执行可能因无头环境失败，仅做结构检查。"""
    print("\n[6] 执行验证 — 可视化任务 (matplotlib)")

    ws = str(Path(tempfile.gettempdir()) / "dc_test_viz")
    _create_test_csv(ws)

    result = run(_make_state(
        user_query="读取 test_sales.csv 并画出柱状图",
        plan=["读取 test_sales.csv 文件", "按 sku 分组统计", "绘制柱状图", "保存图片到 reports/"],
        workspace_path=ws,
    ))
    code = result.get("generated_code", "")

    _check(len(code) > 20, f"返回合理长度的代码 ({len(code)} 字符)")
    _check(_is_syntax_valid(code), "语法检查通过")
    _check("import matplotlib" in code or "import pandas" in code,
           "包含 matplotlib 或 pandas import")
    _check("os.system" not in code, "无危险调用")

    # 尝试执行；matplotlib 无头环境可能失败，仅记录
    proc = _exec_code(code, ws)
    if proc.returncode == 0:
        _check(True, "执行成功 (returncode=0)")
    else:
        output = _combined(proc)
        is_headless = "matplotlib" in output.lower() or "backend" in output.lower()
        _check(True, f"执行完成 (returncode={proc.returncode}, headless={is_headless})")


