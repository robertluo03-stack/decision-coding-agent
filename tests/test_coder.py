def test_safety_helper() -> None:
    print("\n[7] 安全红线 — _has_dangerous_code 辅助函数")

    _check(_has_dangerous_code("import os\nos.system('ls')"), "检测到 os.system")
    _check(_has_dangerous_code("import subprocess\nsubprocess.run(['ls'])"), "检测到 subprocess")
    _check(_has_dangerous_code("eval('1+1')"), "检测到 eval(")
    _check(_has_dangerous_code("exec('x=1')"), "检测到 exec(")
    _check(_has_dangerous_code("__import__('os')"), "检测到 __import__")
    _check(not _has_dangerous_code("import math\nimport pandas as pd\nprint(math.sqrt(4))"),
           "安全代码不误报")


