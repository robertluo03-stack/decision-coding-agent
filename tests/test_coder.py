# ---------------------------------------------------------------------------
# 辅助函数
# ---------------------------------------------------------------------------

def _make_state(
    user_query: str = "",
    plan: list[str] | None = None,
    workspace_path: str | None = None,
    human_feedback: str | None = None,
    retry_count: int = 0,
) -> dict:
    """构造最小 AgentState 字典。"""
    if plan is None:
        plan = []
    if workspace_path is None:
        workspace_path = str(Path(tempfile.gettempdir()) / "dc_test_workspace")

    return {
        "user_query": user_query,
        "workspace_path": workspace_path,
        "plan": plan,
        "generated_code": "",
        "file_path": None,
        "execution_result": None,
        "error": None,
        "retry_count": retry_count,
        "human_feedback": human_feedback,
        "final_report": None,
    }


def _is_syntax_valid(code: str) -> bool:
    """用 compile() 检查代码是否是有效的 Python。"""
    try:
        compile(code, "<test>", "exec")
        return True
    except SyntaxError:
        return False


def _exec_code(code: str, workspace: str) -> subprocess.CompletedProcess:
    """将代码写入临时文件，在给定工作目录下执行。"""
    ws = Path(workspace)
    ws.mkdir(parents=True, exist_ok=True)
    (ws / "data").mkdir(parents=True, exist_ok=True)

    tmp = ws / "_test_exec_temp.py"
    tmp.write_text(code, encoding="utf-8")

    return subprocess.run(
        [sys.executable, str(tmp)],
        capture_output=True,
        text=True,
        timeout=30,
        cwd=str(ws),
    )


def _create_test_csv(workspace: str) -> Path:
    """在工作区 data/ 下创建一个简单的测试 CSV。"""
    data_dir = Path(workspace) / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    csv = data_dir / "test_sales.csv"
    csv.write_text(
        "date,sku,qty,price\n"
        "2024-01-01,SKU001,10,100\n"
        "2024-01-02,SKU001,15,100\n"
        "2024-01-01,SKU002,8,200\n"
        "2024-01-02,SKU002,12,200\n",
        encoding="utf-8",
    )
    return csv


def _combined(proc: subprocess.CompletedProcess) -> str:
    """安全拼接 stdout 与 stderr。"""
    return (proc.stdout or "") + (proc.stderr or "")


# ---------------------------------------------------------------------------
# 统计
# ---------------------------------------------------------------------------

_passed = 0
_failed = 0
_failures: list[str] = []


def _check(condition: bool, name: str, detail: str = "") -> None:
    global _passed, _failed
    if condition:
        _passed += 1
        print(f"  ✅ {name}")
    else:
        _failed += 1
        _failures.append(f"{name}: {detail}")
        print(f"  ❌ {name}  —  {detail}")


# ===================================================================
# 测试 1 — 正常场景：验证生成代码的结构
# ===================================================================

def test_normal_structure() -> None:
    print("\n[1] 正常场景 — 代码结构检查")

    result = run(_make_state(
        user_query="读取 test_sales.csv 统计每个 sku 的总销量",
        plan=["读取 test_sales.csv 文件", "按 sku 分组统计总销量", "输出统计摘要"],
    ))
    code = result.get("generated_code", "")

    _check(len(code) > 20, "返回非空 generated_code")
    _check("import pandas" in code or "import csv" in code, "包含 import 语句")
    _check("print(" in code, "包含 print() 输出")
    _check("os.system" not in code, "不包含 os.system")
    _check("subprocess" not in code, "不包含 subprocess")
    _check("eval(" not in code, "不包含 eval(")
    _check("exec(" not in code, "不包含 exec(")
    _check("data/" in code, "使用相对路径 data/xxx")
    _check(_is_syntax_valid(code), "语法检查通过 (SyntaxError-free)")

    is_fallback = code.startswith("#!/usr/bin/env python3\n# Auto-generated by DecisionCoder (fallback)")
    _check(not is_fallback, "非回退代码（LLM 正常生成）")


