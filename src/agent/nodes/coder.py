"""Coder 节点：根据 Plan 和用户需求使用 DeepSeek API 生成可执行的 Python 代码。

所有生成的代码必须满足：
- 包含所有必要的 import
- 假设数据文件在 ./data/ 目录下（相对路径）
- 使用 print() 展示输出
- 不包含 os.system / subprocess / eval / exec 等危险调用
"""

