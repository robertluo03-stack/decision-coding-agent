"""Coder 节点：根据 Plan 和用户需求使用 DeepSeek API 生成可执行的 Python 代码。

所有生成的代码必须满足：
- 包含所有必要的 import
- 假设数据文件在 ./data/ 目录下（相对路径）
- 使用 print() 展示输出
- 不包含 os.system / subprocess / eval / exec 等危险调用
"""

import os
import re
import textwrap

from src.agent.state import AgentState

# ---------------------------------------------------------------------------
# System prompt for the DeepSeek LLM
# ---------------------------------------------------------------------------

_CODER_SYSTEM_PROMPT = """\
你是一个 Python 数据科学专家。根据给定的执行计划，生成可以直接运行的 Python 代码。

## 环境约束

- Python 3.11+
- 可用库：标准库 + pandas + numpy + matplotlib（均已安装）
- 数据文件在 ./data/ 目录下，使用相对路径读取（如 `data/sales.csv`）
- 输出使用 print()，不使用 logging 模块
- 代码必须自包含，包含所有需要的 import 语句

## 代码要求

- 每个 import 独占一行，放在文件头部
- 文件读取使用相对路径（例如 `pd.read_csv("data/sales.csv")`）
- 对文件操作添加 try/except 错误处理
- 输出信息清晰可读，包含适当的标题分隔

## CSV 列名约束（重要）

读取 CSV 后，必须先用 `df.columns` 或 `df.head(3)` 查看实际列名，再编写后续代码。
- 不要使用假设的列名如 'SKU'、'销量'、'数量'。
- 必须使用文件中的实际列名（如 'sku'、'qty'）。
- 如果用户提到 'sku'，使用实际列名进行分组；如果提到 '销量' 或 '数量'，使用 'qty' 列。

## 严格禁止

绝对不要生成包含以下内容的代码：
- os.system(...)
- subprocess.run(...) 或任何 subprocess 调用
- eval(...)
- exec(...)
- __import__(...)
- shutil.rmtree 或 os.remove 作用于目录
- 任何可能删除用户文件的代码

## 输出格式

只输出 Python 代码，用 ```python ``` 代码块包裹。
代码块之前或之后不要添加任何解释文字。
"""

# ---------------------------------------------------------------------------
# Dangerous pattern check
# ---------------------------------------------------------------------------

_DANGEROUS_PATTERNS = [
    "os.system",
    "subprocess",
    "eval(",
    "exec(",
    "__import__",
]


def _has_dangerous_code(code: str) -> bool:
    """检查代码是否包含危险模式。

    Args:
        code: 生成的 Python 代码

    Returns:
        如果发现危险模式则返回 True
    """
    return any(pattern in code for pattern in _DANGEROUS_PATTERNS)


# ---------------------------------------------------------------------------
# Code extraction from LLM response
# ---------------------------------------------------------------------------


def _extract_code_block(content: str) -> str:
    """从 LLM 响应中提取 Python 代码块。

    优先匹配 ```python ... ``` 格式，
    其次匹配 ``` ... ```（无语言标记），
    最后回退为原始内容。

    Args:
        content: LLM 原始响应文本

    Returns:
        提取出的纯 Python 代码字符串
    """
    # 匹配带语言标记的代码块
    match = re.search(r"```python\s*\n(.*?)```", content, re.DOTALL)
    if match:
        return match.group(1).strip()

    # 匹配无语言标记的代码块
    match = re.search(r"```\s*\n(.*?)```", content, re.DOTALL)
    if match:
        return match.group(1).strip()

    # 回退：直接返回原始内容（去除首尾空白）
    return content.strip()


# ---------------------------------------------------------------------------
# LLM-based code generation
# ---------------------------------------------------------------------------


def _generate_code_with_llm(
    plan: list[str],
    query: str,
    workspace: str,
) -> str:
    """使用 DeepSeek API 生成 Python 代码。

    Args:
        plan: 执行计划步骤列表
        query: 用户原始自然语言需求
        workspace: 工作区绝对路径（仅用于上下文，不硬编码到代码中）

    Returns:
        生成的 Python 代码字符串

    Raises:
        ValueError: 当环境变量 DEEPSEEK_API_KEY 未设置时
    """
    api_key = os.environ.get("DEEPSEEK_API_KEY")
    if not api_key:
        raise ValueError("环境变量 DEEPSEEK_API_KEY 未设置")

    from langchain_deepseek import ChatDeepSeek

    llm = ChatDeepSeek(
        model="deepseek-chat",
        api_key=api_key,
        temperature=0.3,
    )

    # 构造用户消息：将计划和需求组合在一起
    plan_lines = "\n".join(
        f"{i + 1}. {step}" for i, step in enumerate(plan)
    )

    user_message = (
        f"用户需求：{query}\n\n"
        f"执行计划：\n{plan_lines}\n\n"
        f"请按照上述计划生成完整的 Python 代码。"
        f"数据文件放在 ./data/ 目录下，使用相对路径读取。"
        f"输出结果请用 print() 打印。"
    )

    messages = [
        {"role": "system", "content": _CODER_SYSTEM_PROMPT},
        {"role": "user", "content": user_message},
    ]

    response = llm.invoke(messages)
    content = response.content.strip()

    return _extract_code_block(content)


# ---------------------------------------------------------------------------
# Fallback code generation (safe mode)
# ---------------------------------------------------------------------------


def _generate_fallback_code(
    plan: list[str],
    query: str,
    workspace: str,
    error: str | None = None,
) -> str:
    """当 LLM 调用失败或计划异常时，生成安全的回退代码。

    回退代码不会尝试执行任何有意义的分析，
    而是打印错误信息并正常退出，避免崩溃。

    Args:
        plan: 执行计划（可能为空或包含错误信息）
        query: 用户原始需求
        workspace: 工作区路径
        error: 可选的错误描述

    Returns:
        安全的回退 Python 代码
    """
    error_note = f"生成错误: {error}" if error else "未能生成有效代码"
    query_safe = query if (query and query.strip()) else "用户未提供需求"

    lines = [
        "#!/usr/bin/env python3",
        "# Auto-generated by DecisionCoder (fallback)",
        f"# {error_note}",
        f"# 需求: {query_safe}",
        "# 执行计划:",
    ]

    if plan:
        for i, step in enumerate(plan, 1):
            lines.append(f"#   {i}. {step}")
    else:
        lines.append("#   (无有效执行计划)")

    lines.append("")

    # 用纯字符串拼接避免 f-string 中大括号转义混乱
    body = textwrap.dedent("""\
    import sys

    def main():
        print("=" * 60)
        print("DecisionCoder 执行报告 (安全模式)")
        print("=" * 60)
        print()

        query = {query_safe!r}
        plan = {plan_repr!r}

        print(f"原始需求: {{query}}")
        print()

        if plan:
            print("原执行计划:")
            for idx, step in enumerate(plan, 1):
                print(f"  {{idx}}. {{step}}")
        else:
            print("提示: 未能生成有效的执行计划。")
            print("请检查: 1) 需求是否清晰  2) 数据文件是否存在  3) API Key 是否有效")

        print()
        print("结束 (无有效代码可执行)")
        return 0

    if __name__ == "__main__":
        sys.exit(main())
    """)

    # 安全地插入变量值
    body = body.replace("{query_safe!r}", repr(query_safe))
    body = body.replace("{plan_repr!r}", repr(plan))

    return "\n".join(lines) + body


# ---------------------------------------------------------------------------
# Main node entry point
# ---------------------------------------------------------------------------


def coder_node(state: AgentState) -> dict:
    """根据用户需求和执行计划生成可执行的 Python 代码。

    输入: state["user_query"], state["plan"], state["workspace_path"]
    输出: {"generated_code": "完整 Python 代码字符串"}

    如果人在回路提供了 AI_FIX 开头的修复代码，则直接使用。

    Args:
        state: 当前 AgentState

    Returns:
        包含 generated_code 字段的 partial state
    """
    # ---- 人在回路：AI 修复的代码直接使用 ----
    human_feedback = state.get("human_feedback")
    if human_feedback and human_feedback.startswith("AI_FIX:"):
        code = human_feedback[len("AI_FIX:"):].strip()
        return {"generated_code": code, "human_feedback": None}

    # ---- 获取输入 ----
    plan = state.get("plan", [])
    query = state.get("user_query", "")
    workspace = state.get("workspace_path", ".")

    # ---- 边界情况：计划为空或包含错误 ----
    if not plan or any(str(p).startswith("错误") for p in plan):
        return {
            "generated_code": _generate_fallback_code(plan, query, workspace),
        }

    # ---- 边界情况：用户需求为空 ----
    if not query or not query.strip():
        return {
            "generated_code": _generate_fallback_code(
                plan, "", workspace, error="用户需求为空"
            ),
        }

    # ---- 正常路径：使用 DeepSeek LLM 生成代码 ----
    try:
        code = _generate_code_with_llm(plan, query, workspace)
    except Exception as exc:
        return {
            "generated_code": _generate_fallback_code(
                plan, query, workspace, error=str(exc)
            ),
        }

    # ---- 后置安全检查 ----
    if _has_dangerous_code(code):
        return {
            "generated_code": _generate_fallback_code(
                plan, query, workspace, error="LLM 生成代码包含危险调用，已拦截"
            ),
        }

    return {"generated_code": code}


# 别名，兼容 graph.py / Task 7 的 run(state) 约定
run = coder_node
